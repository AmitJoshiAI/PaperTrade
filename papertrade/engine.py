"""Daily engine.

One `run` does, in order:
  1. update   : refresh daily prices from Yahoo.
  2. execute  : fill yesterday's pending orders at TODAY's open (+/- slippage). No look-ahead.
  3. mark     : mark positions to today's close, update stops/highs, append the equity curve.
  4. propose  : evaluate the strategy on today's close and write pending orders for the next session.
  5. thesis   : the separate thesis sleeve (thesis.py): fill queued thesis orders, mark, check invalidations.
  6. F&O, US  : the India F&O sleeve (fno.py, fills at the NSE open) and the US sleeve (us.py, fills at the US
                open); each fills its queued orders, settles expiries, marks, checks its circuit breaker.
  7. review   : write journal/YYYY-MM-DD.md (momentum sections, "## Thesis sleeve", "## India F&O sleeve",
                "## US sleeve", "## All sleeves").

Claude (or you) may edit decisions/pending_orders.json between steps 4 and 2 of the next day.
"""
from __future__ import annotations

import json
import logging
from datetime import datetime

import pandas as pd

from . import config, data, strategy
from .portfolio import Portfolio

log = logging.getLogger(__name__)


def _day(ts) -> str:
    return pd.Timestamp(ts).strftime("%Y-%m-%d")


def load_pending() -> dict:
    if not config.PENDING_ORDERS_FILE.exists():
        return {}
    return json.loads(config.PENDING_ORDERS_FILE.read_text())


def save_pending(decision_date: str, orders: list[dict], note: str = "") -> list[dict]:
    """Write proposals. If the existing file is for the same decision date and has "locked": true
    (a manual override), keep it and return its orders instead. Returns the orders now pending."""
    existing = load_pending()
    if existing.get("decision_date") == decision_date and existing.get("locked"):
        log.info("pending_orders.json for %s is locked (manual override); not overwriting.", decision_date)
        return existing.get("orders", [])
    config.DECISIONS_DIR.mkdir(parents=True, exist_ok=True)
    payload = dict(
        decision_date=decision_date,
        generated_at=datetime.now().isoformat(timespec="seconds"),
        note=note or "Generated by baseline momentum strategy. Edit qty/side or delete lines to override.",
        orders=orders,
    )
    config.PENDING_ORDERS_FILE.write_text(json.dumps(payload, indent=2))
    return orders


def execute_pending(pf: Portfolio, prices: pd.DataFrame) -> list[dict]:
    """Fill pending orders at the first open AFTER the decision date. Returns fills."""
    pending = load_pending()
    if not pending or not pending.get("orders"):
        return []
    decision_date = pd.Timestamp(pending["decision_date"])
    opens = data.pivot(prices, "open")
    later = opens.index[opens.index > decision_date]
    if len(later) == 0:
        log.info("No trading day after %s yet; orders stay pending.", pending["decision_date"])
        return []
    fill_day = later[0]
    fills = []
    sells = [o for o in pending["orders"] if o["side"].upper() == "SELL"]
    buys = [o for o in pending["orders"] if o["side"].upper() == "BUY"]

    for o in sells:
        px = opens.loc[fill_day, o["symbol"]] if o["symbol"] in opens.columns else None
        if px is None or pd.isna(px):
            log.warning("No open price for %s on %s; skipping sell", o["symbol"], fill_day.date())
            continue
        px = float(px) * (1 - config.SLIPPAGE_PCT)
        try:
            qty = int(o["qty"]) if o.get("qty") else pf.positions[o["symbol"]].qty
            fills.append(pf.sell(_day(fill_day), o["symbol"], qty, round(px, 2), o.get("reason", "")))
        except (KeyError, ValueError) as e:
            log.warning("Skipping sell of %s: %s", o["symbol"], e)

    # size buys equally: cash / free slots (after sells), per the strategy rule. Dividing by len(buys)
    # would put the whole account into one stock on a day with a single signal.
    if buys:
        free_slots = max(config.MAX_POSITIONS - len(pf.positions), len(buys))
        per_slot = pf.cash / free_slots * 0.995   # keep a little cash for charges/rounding
        for o in buys:
            px = opens.loc[fill_day, o["symbol"]] if o["symbol"] in opens.columns else None
            if px is None or pd.isna(px):
                log.warning("No open price for %s on %s; skipping buy", o["symbol"], fill_day.date())
                continue
            px = float(px) * (1 + config.SLIPPAGE_PCT)
            qty = int(o["qty"]) if o.get("qty") else int(per_slot // px)
            if qty <= 0:
                log.warning("Not enough cash for one share of %s at %.2f", o["symbol"], px)
                continue
            try:
                fills.append(pf.buy(_day(fill_day), o["symbol"], qty, round(px, 2), o.get("reason", "")))
            except ValueError as e:
                log.warning("%s", e)

    # consume the pending file
    executed = dict(pending)
    executed["executed_on"] = _day(fill_day)
    executed["fills"] = fills
    (config.DECISIONS_DIR / f"executed_{_day(fill_day)}.json").write_text(json.dumps(executed, indent=2, default=str))
    config.PENDING_ORDERS_FILE.unlink()
    return fills


def mark_to_market(pf: Portfolio, prices: pd.DataFrame) -> dict:
    closes = data.pivot(prices, "close")
    last_day = closes.index[-1]
    last = closes.ffill().iloc[-1].to_dict()   # a held name missing today's bar is valued at its last close, not cost
    for sym, pos in pf.positions.items():
        c = last.get(sym)
        if c is not None and not pd.isna(c):
            pos.highest_close = max(pos.highest_close, float(c))
    if pf.start_date is None:
        pf.start_date = _day(last_day)
    row = pf.record_equity(_day(last_day), {k: float(v) for k, v in last.items() if not pd.isna(v)})
    return row


def run_day(do_update: bool = True) -> dict:
    """Full daily cycle. Returns a summary dict for the CLI/review."""
    from . import review  # local import to avoid cycle

    prices = data.update_cache() if do_update else data.load_cache()
    pf = Portfolio.load()
    fills = execute_pending(pf, prices)
    eq_row = mark_to_market(pf, prices)
    closes = data.pivot(prices, "close")
    proposals = strategy.propose(closes, pf)
    today = _day(closes.index[-1])
    proposals = save_pending(today, proposals)
    pf.save()
    # On a same-day re-run the fills already happened in the earlier run; show them from the ledger.
    shown_fills = fills
    if not fills:
        t = Portfolio.trades()
        t = t[t["date"].astype(str) == today]
        shown_fills = [{k: ("" if pd.isna(v) else v) for k, v in r.items()} for r in t.to_dict("records")]
    # Thesis sleeve: a separate book, run only after the momentum sleeve is saved. A failure here must not
    # fail the run (the momentum fills above would not be committed in GitHub Actions).
    thesis_out, thesis_section = None, None
    try:
        from . import thesis
        thesis_out = thesis.run_day(prices, do_update)
        thesis_section = thesis.journal_lines(thesis_out, momentum_equity=eq_row["equity"])
    except Exception:
        log.exception("Thesis sleeve step failed; the momentum sleeve run completed and was saved.")
        thesis_section = ["## Thesis sleeve", "", "**The thesis sleeve step FAILED this run** (see the run log). "
                          "The momentum sleeve above is unaffected."]
    # India F&O and US sleeves: two more separate books, run after the thesis sleeve, each isolated the same way.
    fno_out, us_out = None, None
    try:
        from . import fno
        fno_out = fno.run_day(prices, do_update)
        thesis_section += [""] + fno.journal_lines(fno_out)
    except Exception:
        log.exception("F&O sleeve step failed; the momentum and thesis sleeves completed and were saved.")
        thesis_section += ["", "## India F&O sleeve", "", "**The F&O sleeve step FAILED this run** (see the run log)."]
    try:
        from . import us
        us_out = us.run_day(today, do_update)
        thesis_section += [""] + us.journal_lines(us_out)
    except Exception:
        log.exception("US sleeve step failed; the other sleeves completed and were saved.")
        thesis_section += ["", "## US sleeve", "", "**The US sleeve step FAILED this run** (see the run log)."]
    thesis_section += [""] + combined_lines(eq_row, thesis_out, fno_out, us_out)
    report_path = review.write_daily_review(pf, prices, shown_fills, proposals, dropped=prices.attrs.get("dropped", []),
                                            extra_sections=thesis_section)
    # Dashboard export is read-only and runs after state is saved. A failure here must not fail the run:
    # in GitHub Actions a failed run is not committed, and the fills above would be lost.
    try:
        from .export import write_dashboard_data
        dashboard = str(write_dashboard_data(pf=pf, prices=prices, dropped=prices.attrs.get("dropped")))
    except Exception:
        log.exception("Dashboard export failed; the trading run itself completed and was saved.")
        dashboard = None
    return dict(date=today, fills=fills, equity=eq_row, proposals=proposals, report=str(report_path),
                dashboard=dashboard, thesis=thesis_out, fno=fno_out, us=us_out)


def combined_lines(eq_row: dict, thesis_out, fno_out, us_out) -> list[str]:
    """Journal section: the four sleeves side by side, in INR (US at the fixed USD_INR)."""
    rows = [("Momentum", config.STARTING_CAPITAL, eq_row["equity"]),
            ("Thesis", config.THESIS_CAPITAL, thesis_out["equity"]["equity"] if thesis_out else None),
            ("India F&O", config.FNO_CAPITAL, fno_out["equity"]["equity"] if fno_out else None),
            ("US (at USD_INR %g)" % config.USD_INR, config.US_CAPITAL, us_out["equity"]["equity_inr"] if us_out else None)]
    lines = ["## All sleeves", "", "| Sleeve | Capital | Equity | P&L |", "|---|---|---|---|"]
    for name, cap, eq in rows:
        lines.append(f"| {name} | Rs {cap:,.0f} | " + (f"Rs {eq:,.0f} | Rs {eq - cap:+,.0f} |" if eq is not None else "n/a (step failed) | - |"))
    cap = sum(r[1] for r in rows)
    if all(r[2] is not None for r in rows):
        tot = sum(r[2] for r in rows)
        lines.append(f"| **Combined** | Rs {cap:,.0f} | **Rs {tot:,.0f}** | Rs {tot - cap:+,.0f} ({(tot / cap - 1) * 100:+.2f}%) |")
    return lines
